"use client";

import { Suspense, useEffect, useState } from "react";
import { useRouter, useSearchParams } from "next/navigation";
import Link from "next/link";
import { Logo } from "@/components/Logo";
import { useAuth } from "@/components/AuthProvider";
import { useFetchWithAuth } from "@/hooks/useFetchWithAuth";
import { safeNext } from "@/lib/safeNext";

// ── Response shape helpers ──────────────────────────────────────────────────

type BrandCreateResponse =
  | { brand: { id: string } }
  | { id: string }
  | Record<string, unknown>;

type BrandListItem = { id: string };
type ProductListItem = { id: string; name?: string };

type ProductListResponse = { products: ProductListItem[] } | ProductListItem[];

function extractBrandId(data: BrandCreateResponse): string | null {
  if (data && typeof data === "object") {
    const maybeBrand = (data as { brand?: { id?: unknown } }).brand;
    if (maybeBrand && typeof maybeBrand.id === "string") return maybeBrand.id;
    const maybeId = (data as { id?: unknown }).id;
    if (typeof maybeId === "string") return maybeId;
  }
  return null;
}

// ── Icons ───────────────────────────────────────────────────────────────────

function SpinnerIcon({ className }: { className?: string }) {
  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden="true"
    >
      <circle
        className="opacity-25"
        cx="12"
        cy="12"
        r="10"
        stroke="currentColor"
        strokeWidth="4"
      />
      <path
        className="opacity-75"
        fill="currentColor"
        d="M4 12a8 8 0 018-8v8z"
      />
    </svg>
  );
}

function ArrowRightIcon({ className }: { className?: string }) {
  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      <line x1="5" y1="12" x2="19" y2="12" />
      <polyline points="12 5 19 12 12 19" />
    </svg>
  );
}

// ── Main page ──────────────────────────────────────────────────────────────

function OnboardingPageInner() {
  const router = useRouter();
  const searchParams = useSearchParams();
  const { session, loading } = useAuth();
  const { fetchWithAuth } = useFetchWithAuth();

  // next 파라미터 — guest /quick 흐름에서 가입/온보딩 후 복귀해야 하는 경로.
  // safeNext: root-relative 검증 + 백슬래시 변종 차단 (open-redirect 방지).
  const nextPath = safeNext(searchParams?.get("next"));

  const [step, setStep] = useState<"nickname" | 0>(0);
  const [checking, setChecking] = useState(true);

  // ── Nickname step state ────────────────────────────────────────────────
  const [nicknameInput, setNicknameInput] = useState("");
  const [nicknameInputFocused, setNicknameInputFocused] = useState(false);
  const [nicknameSaving, setNicknameSaving] = useState(false);
  const [nicknameError, setNicknameError] = useState<string | null>(null);

  // ── Brand step state ───────────────────────────────────────────────────
  const [brandName, setBrandName] = useState("");
  const [brandNameFocused, setBrandNameFocused] = useState(false);
  const [brandCreating, setBrandCreating] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // ── Initial check: session → brands → products ─────────────────────────
  useEffect(() => {
    if (loading) return;
    if (!session) {
      // 자체 next 를 login 까지 전달해서 OAuth 후에도 흐름이 살아남도록.
      const loginNext = nextPath
        ? `/onboarding?next=${encodeURIComponent(nextPath)}`
        : "/onboarding";
      router.replace(`/login?next=${encodeURIComponent(loginNext)}`);
      return;
    }

    let cancelled = false;

    const run = async () => {
      try {
        // 0. 닉네임 체크 — 신규 Google 사용자 감지
        const isGoogle =
          session.user.app_metadata?.provider === "google" ||
          (
            session.user.app_metadata?.providers as string[] | undefined
          )?.includes("google");

        if (isGoogle) {
          const profileRes = await fetchWithAuth("/api/profile");
          if (profileRes.ok) {
            const profileData = (await profileRes.json()) as {
              profile?: { nickname?: string };
            };
            const nickname = profileData.profile?.nickname ?? "";
            const isAutoGenerated = /^User-[0-9a-f]{8,}$/.test(nickname);
            if (!nickname || isAutoGenerated) {
              // Google 이름 pre-fill
              const fullName =
                (session.user.user_metadata?.full_name as string | undefined) ??
                (session.user.user_metadata?.name as string | undefined) ??
                "";
              const nicknameRegex = /^[a-zA-Z0-9_ㄱ-힣.-]+$/;
              if (
                fullName &&
                fullName.length >= 1 &&
                fullName.length <= 32 &&
                nicknameRegex.test(fullName)
              ) {
                setNicknameInput(fullName);
              }
              if (cancelled) return;
              setStep("nickname");
              setChecking(false);
              return;
            }
          }
        }
        if (cancelled) return;

        // 1. 브랜드 목록 조회
        const listRes = await fetchWithAuth("/api/brands");
        if (!listRes.ok) throw new Error("브랜드 조회 실패");
        const brands = (await listRes.json()) as BrandListItem[];

        if (cancelled) return;

        if (Array.isArray(brands) && brands.length > 0) {
          // 2-B. 브랜드 있음 → 제품 확인
          const existingBrandId = brands[0].id;
          const prodRes = await fetchWithAuth(
            `/api/brands/${existingBrandId}/products`,
          );
          if (cancelled) return;

          if (prodRes.ok) {
            const json = (await prodRes.json()) as ProductListResponse;
            if (cancelled) return;
            const allProducts = Array.isArray(json)
              ? json
              : ((json as { products: ProductListItem[] }).products ?? []);
            // 테스트 제품은 "실제 등록 제품" 카운트에서 제외
            const commonTestId = process.env.NEXT_PUBLIC_COMMON_TEST_PRODUCT_ID;
            const realProducts = allProducts.filter(
              (p) => p.id !== commonTestId && p.name !== "테스트 제품",
            );
            if (realProducts.length > 0) {
              // 2-B-i. 실제 제품 있음 → next 우선, 없으면 대시보드.
              router.replace(nextPath || `/${existingBrandId}`);
              return;
            }
          }
          // 2-B-ii. 실제 등록 제품 없음 → 이미 온보딩을 거친 사용자 → 탐색/복귀
          router.replace(nextPath || "/explore");
          return;
        }

        // 2-A. 브랜드 없음 → 브랜드 생성 스텝 진입
        setStep(0);
        setChecking(false);
      } catch (err) {
        console.error("[onboarding] initialization failed:", err);
        if (cancelled) return;
        setError("초기 설정에 실패했습니다. 페이지를 새로고침해 주세요.");
        setChecking(false);
      }
    };

    void run();

    return () => {
      cancelled = true;
    };
  }, [loading, session, router, fetchWithAuth, nextPath]);

  // ── Save nickname ───────────────────────────────────────────────────────
  async function handleNicknameSave(e: React.FormEvent) {
    e.preventDefault();
    setNicknameError(null);
    const trimmed = nicknameInput.trim();
    const nicknameRegex = /^[a-zA-Z0-9_ㄱ-힣.-]+$/;
    if (trimmed.length < 1 || trimmed.length > 32) {
      setNicknameError("닉네임은 1~32자여야 합니다.");
      return;
    }
    if (!nicknameRegex.test(trimmed)) {
      setNicknameError(
        "영문, 숫자, 한글, 밑줄(_), 하이픈(-), 점(.)만 사용할 수 있습니다.",
      );
      return;
    }
    setNicknameSaving(true);
    try {
      const res = await fetchWithAuth("/api/profile", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ nickname: trimmed }),
      });
      const data = (await res.json()) as { ok?: boolean; error?: string };
      if (!res.ok) throw new Error(data.error ?? "닉네임 저장에 실패했습니다.");
      setStep(0);
    } catch (err) {
      setNicknameError(
        err instanceof Error ? err.message : "닉네임 저장에 실패했습니다.",
      );
    } finally {
      setNicknameSaving(false);
    }
  }

  // ── Create brand ────────────────────────────────────────────────────────
  async function handleBrandCreate(e: React.FormEvent) {
    e.preventDefault();
    if (!brandName.trim() || brandCreating) return;
    setBrandCreating(true);
    setError(null);
    try {
      const res = await fetchWithAuth("/api/brands", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ name: brandName.trim() }),
      });
      if (!res.ok) throw new Error("브랜드 생성에 실패했습니다.");
      const data = (await res.json()) as BrandCreateResponse;
      const newId = extractBrandId(data);
      if (!newId) throw new Error("브랜드 ID를 받지 못했습니다.");
      // fire-and-forget: 워크스페이스 첫 진입 시 비어 보이지 않게 테스트 제품 자동 생성
      fetchWithAuth(`/api/brands/${newId}/test-product`, {
        method: "POST",
      }).catch((err) => {
        console.warn("[onboarding] test-product fire-and-forget failed:", err);
      });
      // 제품 등록 스텝 없이 바로 라우팅
      router.replace(nextPath || "/explore");
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "브랜드 생성에 실패했습니다.",
      );
      setBrandCreating(false);
    }
  }

  // ── Render: checking ────────────────────────────────────────────────────
  if (loading || checking) {
    return (
      <div
        className="min-h-dvh flex items-center justify-center"
        style={{ background: "#f5f4f4" }}
      >
        <SpinnerIcon className="animate-spin w-6 h-6 text-pink-400" />
      </div>
    );
  }

  // ── Render: nickname step ──────────────────────────────────────────────
  if (step === "nickname") {
    return (
      <div
        className="min-h-dvh"
        style={{ background: "#f5f4f4", position: "relative" }}
      >
        <div className="absolute top-6 left-6 sm:left-8 z-10">
          <Link
            href="/"
            className="inline-flex items-center hover:opacity-80 transition-opacity"
          >
            <Logo width={110} height={28} forceColor="#18181b" />
          </Link>
        </div>

        <div className="relative z-[1] flex flex-col items-center pt-20 sm:pt-28 pb-16 px-4 sm:px-6">
          <div className="w-full max-w-md">
            <h1
              className="text-2xl font-semibold text-center mb-8"
              style={{ color: "#18181b", letterSpacing: "-0.02em" }}
            >
              닉네임을 설정해 주세요
            </h1>

            <form onSubmit={handleNicknameSave}>
              <div
                className="rounded-2xl p-6 space-y-4"
                style={{
                  background: "#ffffff",
                  border: "1px solid rgba(0,0,0,0.08)",
                  boxShadow: "0 4px 16px rgba(0,0,0,0.04), 0 2px 4px rgba(0,0,0,0.04)",
                }}
              >
                <div>
                  <label
                    htmlFor="nickname-input"
                    className="block text-[11px] uppercase tracking-widest font-semibold mb-2"
                    style={{ color: "#be185d" }}
                  >
                    닉네임 *
                  </label>
                  <input
                    id="nickname-input"
                    type="text"
                    className="w-full px-4 py-3 rounded-xl text-sm placeholder:text-zinc-500 outline-none transition-all"
                    style={{
                      background: "#f5f4f4",
                      color: "#18181b",
                      border: nicknameInputFocused
                        ? "1px solid rgba(255,164,198,0.5)"
                        : "1px solid rgba(0,0,0,0.1)",
                      boxShadow: nicknameInputFocused
                        ? "0 0 0 3px rgba(255,164,198,0.2)"
                        : "none",
                    }}
                    placeholder="영문, 숫자, 한글, -, _"
                    value={nicknameInput}
                    onChange={(e) => setNicknameInput(e.target.value)}
                    onFocus={() => setNicknameInputFocused(true)}
                    onBlur={() => setNicknameInputFocused(false)}
                    disabled={nicknameSaving}
                    autoFocus
                    minLength={1}
                    maxLength={32}
                    required
                  />
                </div>

                {nicknameError && (
                  <div
                    role="alert"
                    className="rounded-xl px-4 py-3 text-sm"
                    style={{
                      color: "#b91c1c",
                      background: "rgba(248,113,113,0.08)",
                      border: "1px solid rgba(220,38,38,0.25)",
                    }}
                  >
                    {nicknameError}
                  </div>
                )}
              </div>

              <button
                type="submit"
                disabled={!nicknameInput.trim() || nicknameSaving}
                className="mt-6 w-full flex items-center justify-center gap-2.5 pl-6 pr-2.5 py-4 rounded-full text-base font-bold active:scale-95 disabled:opacity-50 disabled:cursor-not-allowed transition-transform"
                style={{
                  background: "linear-gradient(135deg, #ffa4c6, #ffe3be)",
                  color: "#000",
                  boxShadow: "0 6px 20px rgba(255,164,198,0.45), 0 2px 4px rgba(0,0,0,0.06)",
                }}
              >
                {nicknameSaving ? (
                  <>
                    <SpinnerIcon className="animate-spin w-4 h-4" />
                    <span>저장 중…</span>
                  </>
                ) : (
                  <>
                    <span>저장하고 계속하기</span>
                    <span className="w-8 h-8 rounded-full bg-black/10 flex items-center justify-center">
                      <ArrowRightIcon className="w-4 h-4" />
                    </span>
                  </>
                )}
              </button>
            </form>
          </div>
        </div>
      </div>
    );
  }

  // ── Render: brand step (단일 메인 스텝) ─────────────────────────────────
  return (
    <div
      className="min-h-dvh"
      style={{ background: "#f5f4f4", position: "relative" }}
    >
      {/* 좌상단 로고 */}
      <div className="absolute top-6 left-6 sm:left-8 z-10">
        <Link
          href="/"
          className="inline-flex items-center hover:opacity-80 transition-opacity"
        >
          <Logo width={110} height={28} forceColor="#18181b" />
        </Link>
      </div>

      <div className="relative z-[1]">
        {/* 헤더 영역 */}
        <div className="max-w-2xl mx-auto px-4 sm:px-6 pt-20 sm:pt-28 pb-10 text-center">
          <h1
            className="text-2xl font-semibold mb-3"
            style={{ color: "#18181b", letterSpacing: "-0.02em" }}
          >
            브랜드 이름을 입력해주세요
          </h1>
        </div>

        {/* 폼 영역 */}
        <div className="max-w-md mx-auto px-4 sm:px-6 pb-16">
          <form onSubmit={handleBrandCreate}>
            <div
              className="rounded-2xl p-6 space-y-5"
              style={{
                background: "#ffffff",
                border: "1px solid rgba(0,0,0,0.08)",
                boxShadow: "0 4px 16px rgba(0,0,0,0.04), 0 2px 4px rgba(0,0,0,0.04)",
              }}
            >
              <div>
                <label
                  htmlFor="brand-name"
                  className="block text-[11px] uppercase tracking-widest font-semibold mb-2"
                  style={{ color: "#be185d" }}
                >
                  브랜드 이름 *
                </label>
                <input
                  id="brand-name"
                  type="text"
                  className="w-full px-4 py-3 rounded-xl text-sm placeholder:text-zinc-500 outline-none transition-all"
                  style={{
                    background: "#f5f4f4",
                    color: "#18181b",
                    border: brandNameFocused
                      ? "1px solid rgba(255,164,198,0.5)"
                      : "1px solid rgba(0,0,0,0.1)",
                    boxShadow: brandNameFocused
                      ? "0 0 0 3px rgba(255,164,198,0.2)"
                      : "none",
                  }}
                  placeholder="예: 블루밍"
                  value={brandName}
                  onChange={(e) => setBrandName(e.target.value)}
                  onFocus={() => setBrandNameFocused(true)}
                  onBlur={() => setBrandNameFocused(false)}
                  disabled={brandCreating}
                  autoFocus
                  required
                  maxLength={80}
                />
              </div>
            </div>

            {error && (
              <div
                role="alert"
                className="mt-4 rounded-2xl px-6 py-4 text-sm"
                style={{
                  color: "#b91c1c",
                  background: "rgba(248,113,113,0.08)",
                  border: "1px solid rgba(220,38,38,0.25)",
                }}
              >
                {error}
              </div>
            )}

            <button
              type="submit"
              disabled={!brandName.trim() || brandCreating}
              className="mt-6 w-full flex items-center justify-center gap-2.5 pl-6 pr-2.5 py-4 rounded-full text-base font-bold active:scale-95 disabled:opacity-50 disabled:cursor-not-allowed transition-transform"
              style={{
                background: "linear-gradient(135deg, #ffa4c6, #ffe3be)",
                color: "#000",
                boxShadow: "0 6px 20px rgba(255,164,198,0.45), 0 2px 4px rgba(0,0,0,0.06)",
              }}
            >
              {brandCreating ? (
                <>
                  <SpinnerIcon className="animate-spin w-4 h-4" />
                  <span>생성 중…</span>
                </>
              ) : (
                <>
                  <span>시작하기</span>
                  <span className="w-8 h-8 rounded-full bg-black/10 flex items-center justify-center">
                    <ArrowRightIcon className="w-4 h-4" />
                  </span>
                </>
              )}
            </button>
          </form>
        </div>
      </div>
    </div>
  );
}

// useSearchParams 는 Next.js 15 에서 Suspense 경계가 필요하다.
// guest /quick 흐름에서 ?next= 를 읽기 위해 useSearchParams 를 사용하므로
// 페이지 전체를 Suspense 로 감싸 prerender 안전성을 확보한다.
export default function OnboardingPage() {
  return (
    <Suspense
      fallback={
        <div
          className="min-h-dvh flex items-center justify-center"
          style={{ background: "#f5f4f4" }}
        >
          <SpinnerIcon className="animate-spin w-6 h-6 text-pink-400" />
        </div>
      }
    >
      <OnboardingPageInner />
    </Suspense>
  );
}
